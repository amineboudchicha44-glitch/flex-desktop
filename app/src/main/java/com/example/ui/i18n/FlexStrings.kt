enum class AppLanguage(val key: String, val englishLabel: String, val arabicLabel: String) {
    AUTO("auto", "System Default", "لغة النظام"),
    ENGLISH("en", "English", "English"),
    ARABIC("ar", "Arabic (العربية)", "العربية");

    companion object {
        fun fromKey(key: String?): AppLanguage =
            entries.firstOrNull { it.key == key } ?: AUTO
    }

    fun isArabicResolved(): Boolean = when (this) {
        ARABIC -> true
        ENGLISH -> false
        AUTO -> Locale.getDefault().language == "ar"
    }
}

